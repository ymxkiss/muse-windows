'use strict';
// Run with: xvfb-run -a node_modules/.bin/electron --no-sandbox test/electron-environment.cjs
const { app, BrowserWindow, session } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { loadOrCreateEnvironment, applyEnvironment } = require('../src/browser-environment');
const root = process.env.MUSE_TEST_ROOT || fs.mkdtempSync(path.join(os.tmpdir(), 'muse-integration-'));
fs.mkdirSync(root, {recursive:true});
const recordFile = path.join(root, 'verification.json');
const previous = fs.existsSync(recordFile) ? JSON.parse(fs.readFileSync(recordFile, 'utf8')) : null;
app.setPath('userData', root);
const profile = loadOrCreateEnvironment(root);
let server;
let browser;
setTimeout(() => { console.error('Integration test exceeded 40 seconds'); app.exit(2); }, 40000).unref();
(async () => {
  console.log('phase: waiting for Electron ready');
  await app.whenReady();
  console.log('phase: Electron ready');
  const requests = [];
  server = http.createServer((request, response) => {
    requests.push(request.headers);
    response.setHeader('Content-Type', 'text/html');
    response.end(request.url === '/' ? '<!doctype html><title>Environment test</title><iframe src="/frame"></iframe>' : '<!doctype html><title>Frame</title>');
  });
  await new Promise((resolve) => server.listen(previous?.port || 0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}/`;
  const partition = `persist:muse-${profile.id}`;
  const browserSession = session.fromPartition(partition);
  const ua = `Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/${process.versions.chrome} Safari/537.36`;
  browser = new BrowserWindow({ show: false, webPreferences: { session: browserSession, sandbox: true, contextIsolation: true } });
  console.log('phase: applying environment');
  await applyEnvironment(browser.webContents, browserSession, profile, ua, process.versions.chrome);
  console.log('phase: loading local test page');
  await browser.loadURL(url);
  console.log('phase: reading page values');
  const collect = `({ua:navigator.userAgent,languages:[...navigator.languages],locale:Intl.DateTimeFormat().resolvedOptions().locale,timezone:Intl.DateTimeFormat().resolvedOptions().timeZone,cpu:navigator.hardwareConcurrency,screen:{width:screen.width,height:screen.height,dpr:devicePixelRatio},platform:navigator.platform,brands:navigator.userAgentData?.brands})`;
  const actual = await browser.webContents.executeJavaScript(collect);
  assert.equal(actual.ua, ua);
  assert.deepEqual(actual.languages, profile.languages);
  assert.equal(new Intl.Locale(actual.locale).language, new Intl.Locale(profile.locale).language);
  assert.equal(actual.timezone, new Intl.DateTimeFormat('en', {timeZone:profile.timezoneId}).resolvedOptions().timeZone);
  assert.equal(actual.cpu, profile.hardwareConcurrency);
  assert.equal(actual.platform, profile.platform);
  assert.deepEqual(actual.screen, {width:profile.screen.width,height:profile.screen.height,dpr:profile.screen.deviceScaleFactor});
  assert.equal(requests[0]['user-agent'], ua);
  assert.ok(requests[0]['accept-language'].startsWith(profile.languages[0]));
  assert.ok(actual.brands.some((brand) => brand.brand === 'Chromium'));
  const before = JSON.stringify(actual);
  if (previous) {
    assert.equal(before, previous.actual);
    assert.equal(await browser.webContents.executeJavaScript("localStorage.getItem('restart-test')"), 'kept');
    assert.ok((await browserSession.cookies.get({url})).some((cookie) => cookie.name === 'muse_test'));
    console.log('Cross-process restart: environment, cookie and localStorage retained');
  }
  await browser.webContents.executeJavaScript("localStorage.setItem('restart-test','kept'); document.cookie='muse_test=kept; path=/; max-age=3600'");
  await browserSession.cookies.flushStore();
  browserSession.flushStorageData();
  const reloaded = new Promise((resolve) => browser.webContents.once('did-finish-load', resolve));
  browser.webContents.reload();
  await reloaded;
  assert.equal(JSON.stringify(await browser.webContents.executeJavaScript(collect)), before);
  assert.equal(await browser.webContents.executeJavaScript("localStorage.getItem('restart-test')"), 'kept');
  assert.ok((await browserSession.cookies.get({url})).some((cookie) => cookie.name === 'muse_test'));
  assert.deepEqual(loadOrCreateEnvironment(root), profile);
  console.log(JSON.stringify({result:'PASS',chrome:process.versions.chrome,actual,storage:'cookie/localStorage retained on reload',profile:'same on reread'},null,2));
  fs.writeFileSync(recordFile, JSON.stringify({port:server.address().port,actual:before}));
  browser.destroy();
  await browserSession.closeAllConnections();
  server.close();
  app.exit(0);
})().catch((error) => {
  console.error(error);
  browser?.destroy();
  server?.close();
  app.exit(1);
});
